import type { Client } from '@libsql/client';

export async function runMigrations(db: Client): Promise<void> {
  await db.batch(
    [
      `CREATE TABLE IF NOT EXISTS sources (
        id TEXT PRIMARY KEY,
        name TEXT NOT NULL,
        kind TEXT NOT NULL,
        homepage TEXT,
        cadence TEXT NOT NULL,
        enabled INTEGER NOT NULL DEFAULT 1,
        last_attempt_at INTEGER,
        last_success_at INTEGER,
        last_error TEXT,
        last_duration_ms INTEGER,
        items_found INTEGER NOT NULL DEFAULT 0,
        items_new INTEGER NOT NULL DEFAULT 0
      )`,
      `CREATE TABLE IF NOT EXISTS news (
        id TEXT PRIMARY KEY,
        source_id TEXT NOT NULL,
        source_name TEXT NOT NULL,
        kind TEXT NOT NULL,
        title TEXT NOT NULL,
        url TEXT NOT NULL,
        summary TEXT,
        author TEXT,
        version TEXT,
        published_at INTEGER,
        discovered_at INTEGER NOT NULL,
        updated_at INTEGER NOT NULL,
        has_feature INTEGER NOT NULL DEFAULT 0,
        has_bugfix INTEGER NOT NULL DEFAULT 0,
        has_compat INTEGER NOT NULL DEFAULT 0,
        has_performance INTEGER NOT NULL DEFAULT 0,
        has_anticheat INTEGER NOT NULL DEFAULT 0,
        has_newly_playable INTEGER NOT NULL DEFAULT 0,
        has_discussion INTEGER NOT NULL DEFAULT 0,
        categories TEXT NOT NULL DEFAULT '[]',
        games TEXT NOT NULL DEFAULT '[]',
        raw TEXT
      )`,
      `CREATE TABLE IF NOT EXISTS news_entries (
        id TEXT PRIMARY KEY,
        news_id TEXT NOT NULL,
        idx INTEGER NOT NULL,
        section TEXT,
        text TEXT NOT NULL,
        category TEXT NOT NULL,
        has_feature INTEGER NOT NULL DEFAULT 0,
        has_bugfix INTEGER NOT NULL DEFAULT 0,
        has_compat INTEGER NOT NULL DEFAULT 0,
        has_performance INTEGER NOT NULL DEFAULT 0,
        has_anticheat INTEGER NOT NULL DEFAULT 0,
        has_newly_playable INTEGER NOT NULL DEFAULT 0,
        games TEXT NOT NULL DEFAULT '[]',
        external_url TEXT,
        FOREIGN KEY (news_id) REFERENCES news(id) ON DELETE CASCADE
      )`,
      `CREATE TABLE IF NOT EXISTS news_games (
        news_id TEXT NOT NULL,
        appid INTEGER NOT NULL,
        name TEXT NOT NULL,
        PRIMARY KEY (news_id, appid),
        FOREIGN KEY (news_id) REFERENCES news(id) ON DELETE CASCADE
      )`,
      `CREATE TABLE IF NOT EXISTS games (
        appid INTEGER PRIMARY KEY,
        name TEXT NOT NULL,
        name_key TEXT NOT NULL,
        header_image TEXT,
        store_url TEXT,
        tier TEXT,
        trending_tier TEXT,
        best_tier TEXT,
        score REAL,
        confidence TEXT,
        reports INTEGER,
        is_native INTEGER NOT NULL DEFAULT 0,
        featured INTEGER NOT NULL DEFAULT 0,
        lookup INTEGER NOT NULL DEFAULT 0,
        release_date TEXT,
        discovered_at INTEGER NOT NULL,
        fetched_at INTEGER NOT NULL,
        previous_tier TEXT,
        tier_changed_at INTEGER,
        awa_status TEXT,
        awa_anticheats TEXT,
        awa_native INTEGER NOT NULL DEFAULT 0,
        awa_url TEXT,
        awa_updated_at INTEGER
      )`,
      `CREATE TABLE IF NOT EXISTS game_history (
        appid INTEGER NOT NULL,
        day INTEGER NOT NULL,
        tier TEXT,
        trending_tier TEXT,
        score REAL,
        reports INTEGER,
        captured_at INTEGER NOT NULL,
        PRIMARY KEY (appid, day),
        FOREIGN KEY (appid) REFERENCES games(appid) ON DELETE CASCADE
      )`,
      `CREATE TABLE IF NOT EXISTS compat_events (
        id TEXT PRIMARY KEY,
        appid INTEGER,
        game_name TEXT NOT NULL,
        event_type TEXT NOT NULL,
        from_value TEXT,
        to_value TEXT NOT NULL,
        created_at INTEGER NOT NULL,
        url TEXT
      )`,
      `CREATE TABLE IF NOT EXISTS anticheat (
        id TEXT PRIMARY KEY,
        name TEXT NOT NULL,
        name_key TEXT NOT NULL,
        appid INTEGER,
        status TEXT NOT NULL,
        anticheats TEXT NOT NULL DEFAULT '[]',
        native INTEGER NOT NULL DEFAULT 0,
        notes TEXT NOT NULL DEFAULT '[]',
        reference TEXT,
        url TEXT,
        updated_at INTEGER,
        fetched_at INTEGER NOT NULL
      )`,
      `CREATE TABLE IF NOT EXISTS fetch_log (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        source TEXT NOT NULL,
        started_at INTEGER NOT NULL,
        duration_ms INTEGER NOT NULL,
        items_found INTEGER NOT NULL DEFAULT 0,
        items_new INTEGER NOT NULL DEFAULT 0,
        error TEXT
      )`,
      `CREATE TABLE IF NOT EXISTS meta (
        key TEXT PRIMARY KEY,
        value TEXT NOT NULL
      )`,
      `CREATE TABLE IF NOT EXISTS search_cache (
        query_key TEXT PRIMARY KEY,
        payload TEXT NOT NULL,
        fetched_at INTEGER NOT NULL
      )`,
      `CREATE INDEX IF NOT EXISTS idx_news_date ON news(COALESCE(published_at, discovered_at) DESC)`,
      `CREATE INDEX IF NOT EXISTS idx_news_source ON news(source_id)`,
      `CREATE INDEX IF NOT EXISTS idx_news_kind ON news(kind)`,
      `CREATE INDEX IF NOT EXISTS idx_news_feature ON news(has_feature)`,
      `CREATE INDEX IF NOT EXISTS idx_news_bugfix ON news(has_bugfix)`,
      `CREATE INDEX IF NOT EXISTS idx_news_compat ON news(has_compat)`,
      `CREATE INDEX IF NOT EXISTS idx_news_discussion ON news(has_discussion)`,
      `CREATE INDEX IF NOT EXISTS idx_entries_news ON news_entries(news_id, idx)`,
      `CREATE INDEX IF NOT EXISTS idx_entries_bugfix ON news_entries(has_bugfix)`,
      `CREATE INDEX IF NOT EXISTS idx_entries_compat ON news_entries(has_compat)`,
      `CREATE INDEX IF NOT EXISTS idx_news_games_appid ON news_games(appid)`,
      `CREATE INDEX IF NOT EXISTS idx_games_featured ON games(featured, tier)`,
      `CREATE INDEX IF NOT EXISTS idx_games_name ON games(name_key)`,
      `CREATE INDEX IF NOT EXISTS idx_games_tier ON games(tier)`,
      `CREATE INDEX IF NOT EXISTS idx_history_appid ON game_history(appid, day)`,
      `CREATE INDEX IF NOT EXISTS idx_events_created ON compat_events(created_at DESC)`,
      `CREATE INDEX IF NOT EXISTS idx_events_appid ON compat_events(appid)`,
      `CREATE INDEX IF NOT EXISTS idx_anticheat_appid ON anticheat(appid)`,
      `CREATE INDEX IF NOT EXISTS idx_anticheat_name ON anticheat(name_key)`,
    ],
    'write',
  );
}
